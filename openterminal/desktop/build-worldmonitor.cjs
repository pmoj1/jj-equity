const fs = require('node:fs');
const path = require('node:path');
const { execFileSync: run } = require('node:child_process');
const wm = path.resolve(__dirname,'../../worldmonitor');
if(!fs.existsSync(path.join(wm,'package.json'))) throw new Error('Place the included worldmonitor source folder beside openterminal before building.');
const options = { cwd:wm, stdio:'inherit' };
run('npm',['ci','--ignore-scripts'],options);
for(const script of ['scripts/generate-inventory-facts.mjs','docker/build-handlers.mjs']) run(process.execPath,[script],options);
run(process.execPath,['node_modules/.bin/tsc','--noEmit'],options);
run(process.execPath,['node_modules/vite/bin/vite.js','build'],options);
const deps = path.resolve(__dirname,'../../work/wm-runtime-deps');
fs.mkdirSync(deps,{recursive:true});
fs.copyFileSync(path.join(wm,'docker/runtime-package.json'),path.join(deps,'package.json'));
fs.copyFileSync(path.join(wm,'docker/runtime-package-lock.json'),path.join(deps,'package-lock.json'));
run('npm',['ci','--omit=dev','--omit=optional','--ignore-scripts'],{cwd:deps,stdio:'inherit'});
