// Build a local Apple Silicon disk image using macOS tools.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync: run } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const work = process.env.JJ_PACKAGE_WORK || fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'jj-equity-package-'));
const output = process.env.JJ_OUTPUT_DIR || path.resolve(root, '../outputs');
const config = require('./package.json');
const version = config.build.electronVersion;
fs.mkdirSync(work, { recursive: true });
fs.mkdirSync(output, { recursive: true });
const zip = path.join(work, 'electron.zip');
if (!fs.existsSync(zip)) run('curl', ['-fL', `https://github.com/electron/electron/releases/download/v${version}/electron-v${version}-darwin-arm64.zip`, '-o', zip], {stdio:'inherit'});
const unpack = path.join(work, 'unpack');
fs.rmSync(unpack, {recursive:true,force:true});
run('ditto', ['-x', '-k', zip, unpack]);
const image = path.join(work, 'image');
fs.rmSync(image, {recursive:true,force:true});
fs.mkdirSync(image);
const app = path.join(image, 'J&J Equity.app');
fs.renameSync(path.join(unpack,'Electron.app'), app);
const plist = path.join(app,'Contents/Info.plist');
for (const [key, value] of Object.entries({CFBundleDisplayName:'J&J Equity',CFBundleName:'J&J Equity',CFBundleIdentifier:'com.jjequity.desktop',CFBundleShortVersionString:config.version,CFBundleVersion:config.version,LSApplicationCategoryType:'public.app-category.finance'})) run('plutil', ['-replace',key,'-string',value,plist]);
const resources = path.join(app,'Contents/Resources');
fs.mkdirSync(path.join(resources,'app'));
for(const name of ['main.cjs','package.json']) fs.copyFileSync(path.join(__dirname,name),path.join(resources,'app',name));
fs.cpSync(path.join(__dirname,'runtime'),path.join(resources,'runtime'),{recursive:true,verbatimSymlinks:true});
fs.rmSync(path.join(resources,'default_app.asar'),{force:true});
fs.copyFileSync(path.join(output,'J&J-Equity-Source.zip'),path.join(resources,'J&J-Equity-Source.zip'));
run('xattr',['-cr',app]);
run('codesign',['--force','--deep','--sign','-',app],{stdio:'inherit'});
fs.symlinkSync('/Applications',path.join(image,'Applications'));
run('hdiutil',['create','-volname','J&J Equity','-srcfolder',image,'-ov','-format','UDZO',path.join(output,`J&J-Equity-${config.version}-arm64.dmg`)],{stdio:'inherit'});
